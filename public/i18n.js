let current = "es";

export function setLang(lang) {
  current = DICT[lang] ? lang : "es";
  if (typeof document !== "undefined") document.documentElement.lang = current === "es" ? "es-MX" : current;
}

export function getLang() {
  return current;
}

/** ブラウザの言語から初期言語を決める(該当なしはスペイン語) */
export function detectLang(navLangs = []) {
  for (const l of navLangs) {
    const base = String(l).slice(0, 2).toLowerCase();
    if (DICT[base]) return base;
  }
  return "es";
}

export function t(key, vars = {}) {
  const s = DICT[current][key] ?? DICT.es[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

/** data-i18n / data-i18n-placeholder 属性の付いた要素に文言を入れる */
export function applyI18n(root) {
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = t(el.dataset.i18nPlaceholder);
}

